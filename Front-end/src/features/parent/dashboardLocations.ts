export function getRegionForDistrict(district: string) {
  const normalizedDistrict = district.trim().toLocaleLowerCase();
  return locationRegions.find((region) =>
    region.districts.some((item) => item.toLocaleLowerCase() === normalizedDistrict),
  );
}
